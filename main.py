# Cambiar el tipo de expresión: typecasting
float(2) # => 2.0
int(4.4) # => 4
int('1') # => 1
int('A') # => ValueError: invalid literal for int() with base 10: 'A'
str(1) # => '1'
str(4.4) # => '4.4'
int(True) # => 1
int(False) # => 0
bool(1) # => True
bool(0) # => False
